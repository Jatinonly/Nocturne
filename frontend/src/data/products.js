function slugify(value) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
}

/*
    stockFor() generates deterministic pseudo-random stock quantities for each product size.
    It uses a seed made from the product ID and name, converts that seed into a hash value,
    and then derives stock numbers from the hash. Because the same seed always produces the same result,
    the stock remains consistent across reloads or repeated seeding instead of changing randomly.
    It also supports a soldOut flag, which sets stock to zero for all sizes 
 */
function stockFor(seed, sizes, soldOut = false) {
  let hash = 0
  for (const char of seed) hash = (hash * 31 + char.charCodeAt(0)) >>> 0
  return Object.fromEntries(
    sizes.map((size, index) => {
      if (soldOut) return [size, 0]
      const value = (hash >>> (index * 3)) % 9
      // Roughly 1 in 6 sizes sold out, a few with low stock.
      return [size, value === 0 ? 0 : value < 3 ? value : value + 3]
    }),
  )
}

function sizesFor(category) {
  if (category === 'women' || category === 'men') return SIZES[category]
  if (category === 'shoes') return SIZES.shoes
  return SIZES.one
}

const BASE_DATE = new Date('2026-10-01T10:00:00Z').getTime()
const DAY = 86_400_000

function build(seed, index) {
  const sizes = sizesFor(seed.category)
  const id = `p${String(index + 1).padStart(3, '0')}`
  return {
    id,
    // slug is a URL-friendly version of the product name, usually used to identify a product in a web URL.
    slug: `${slugify(seed.name)}-${id}`,
    name: seed.name,
    description: seed.description,
    category: seed.category,
    subcategory: seed.subcategory,
    price: seed.price,
    compareAtPrice: seed.compareAt,
    colours: seed.colours.map((key) => COLOURS[key]),
    sizes,
    stock: stockFor(id + seed.name, sizes, seed.soldOut),
    rating: seed.rating,
    reviewCount: seed.reviews,
    tags: [...(seed.tags ?? []), ...(seed.daysAgo <= 21 ? ['new'] : [])],
    silhouette: seed.silhouette,
    composition: seed.composition,
    details: seed.details ?? DEFAULT_DETAILS[seed.category],
    createdAt: new Date(BASE_DATE - seed.daysAgo * DAY).toISOString(),
  }
}

